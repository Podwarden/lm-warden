#!/usr/bin/env bash
# lock-requirements.sh — regenerate requirements-macos.txt from requirements-macos.in.
#
#   scripts/macos/lock-requirements.sh            rewrite requirements-macos.txt
#   scripts/macos/lock-requirements.sh --check    re-resolve to a temp file and diff; exit 1 on drift
#
# Tooling: `uv pip compile` (uv is what the macOS lane already uses to build its
# venvs — provision-macos.sh step 4, test:macos in .gitlab-ci.yml). requirements.txt
# itself is hand-pinned with no lock tool, so there is nothing to "match" there.
#
# Target: the bundle's interpreter — CPython 3.12 on arm64 macOS 14+ — wheels only
# (`--no-build`: a signed bundle must never compile at install time, and every
# package here has an arm64/universal2 wheel). Hashes are generated so the bundle
# build installs with `pip install --require-hashes --only-binary :all:` (or
# `uv pip install --require-hashes`).
#
# Run it on an Apple Silicon Mac (the M1 lane host): the resolution is pinned to
# the target platform by flags, but the --check diff is only meaningful against
# the index the bundle build sees. The resolve is cut off at EXCLUDE_NEWER, so
# --check stays reproducible and a re-lock cannot pull in newer releases.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
IN="requirements-macos.in"
OUT="requirements-macos.txt"
PYVER="3.12"
PLATFORM="aarch64-apple-darwin"
# UTC cutoff for `uv pip compile`: uv ignores any release uploaded after it, so
# --check and re-locks stay reproducible (a day-old release cannot slip in
# unreviewed). Bumping it is a deliberate, reviewed edit made in the same
# commit as a re-lock (e.g. when a requirements.txt pin needs a newer release).
EXCLUDE_NEWER="2026-10-21T01:39:02Z"
# The app's floor (Package.swift .macOS(.v14), Info.plist LSMinimumSystemVersion 14.0). uv reads the
# macOS version for --python-platform from MACOSX_DEPLOYMENT_TARGET; without it uv assumes 12.0 and
# rejects mlx, whose oldest arm64 wheel is macosx_14_0.
export MACOSX_DEPLOYMENT_TARGET="14.0"

command -v uv >/dev/null 2>&1 || { echo "lock-requirements.sh: uv not found on PATH" >&2; exit 2; }

compile() {
  # $1 = output path (relative to ROOT so the header's command line is stable)
  (cd "$ROOT" && uv pip compile "$IN" \
    --output-file "$1" \
    --python-version "$PYVER" \
    --python-platform "$PLATFORM" \
    --no-build \
    --exclude-newer "$EXCLUDE_NEWER" \
    --generate-hashes \
    --no-header \
    --quiet)
  # A fixed header instead of uv's (which embeds the output path and uv flags verbatim).
  local tmp; tmp="$(mktemp)"
  {
    echo "# GENERATED by scripts/macos/lock-requirements.sh from $IN — do not edit."
    echo "# Target: CPython $PYVER, $PLATFORM (macOS >= $MACOSX_DEPLOYMENT_TARGET), wheels only. Regenerate: make macos-requirements"
    cat "$ROOT/$1"
  } >"$tmp"
  mv "$tmp" "$ROOT/$1"
}

case "${1:-}" in
  --check)
    rel=".lock-check-$$.txt"
    trap 'rm -f "$ROOT/$rel"' EXIT
    compile "$rel"
    if diff -u "$ROOT/$OUT" "$ROOT/$rel"; then
      echo "ok $OUT matches a fresh resolve of $IN"
    else
      echo "drift: $OUT differs from a fresh resolve of $IN (run make macos-requirements)" >&2
      exit 1
    fi
    ;;
  "")
    compile "$OUT"
    echo "wrote $OUT"
    ;;
  -h|--help)
    sed -n '2,6p' "$0"
    ;;
  *)
    echo "usage: $0 [--check]" >&2; exit 2 ;;
esac
