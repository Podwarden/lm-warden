"""Sparkle update detection against a local appcast (P8, sparkle-updater).

Selected only under ``-m macos``. Builds the real ``LMWarden`` binary, assembles
an ad-hoc signed bundle (``com.podwarden.lmwarden.updprobe``) with the pinned,
embedded Sparkle.framework and an OLD ``CFBundleVersion`` (1), serves an
appcast from a ``127.0.0.1`` HTTP server owned by the test, and runs
``LMWarden --update-probe`` from inside the bundle: one informational Sparkle
check (no UI, nothing downloaded or installed). It asserts:

- a newer item (``sparkle:version`` 2) is detected,
- an item at the same version is not,
- a bundle without SUFeedURL / SUPublicEDKey (a dev build) has the updater
  disabled and never touches the feed.

The EdDSA key is THROWAWAY: generated by this test in a temp dir it deletes
afterwards (asserted). It never enters the Keychain: Sparkle's
``generate_keys`` can only store keys there, so the keypair is made with
``cryptography`` (Ed25519 seed, the same format ``generate_keys -x`` exports)
and Sparkle's own ``sign_update --ed-key-file`` from the pinned distribution
signs the enclosure; the signature is checked against the public half that
goes in the bundle's SUPublicEDKey. Nothing is committed or kept.

Isolation: the probe bundle id has its own defaults domain and caches, removed
before and after. Skips only off Apple Silicon macOS; anything else fails.
"""

from __future__ import annotations

import base64
import http.server
import os
import platform
import plistlib
import shutil
import subprocess
import sys
import tempfile
import threading
import zipfile
from collections.abc import Iterator
from pathlib import Path

import pytest

pytestmark = pytest.mark.macos

REPO = Path(__file__).resolve().parents[2]
MACOS = REPO / "scripts" / "macos"
PROBE_ID = "com.podwarden.lmwarden.updprobe"

if sys.platform != "darwin" or platform.machine() != "arm64":
    pytest.skip("needs Apple Silicon macOS", allow_module_level=True)


def _run(cmd: list[str], timeout: float = 900, **kw: object) -> subprocess.CompletedProcess[str]:
    done = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, check=False, **kw)  # type: ignore[call-overload]
    assert (
        done.returncode == 0
    ), f"{cmd[0]} failed ({done.returncode}):\n{done.stdout[-2000:]}\n{done.stderr[-2000:]}"
    return done  # type: ignore[no-any-return]


def _clean_probe_state() -> None:
    subprocess.run(["defaults", "delete", PROBE_ID], capture_output=True, check=False)
    home = Path.home()
    for d in (home / "Library" / "Caches" / PROBE_ID, home / "Library" / "HTTPStorages" / PROBE_ID):
        shutil.rmtree(d, ignore_errors=True)
    (home / "Library" / "Preferences" / f"{PROBE_ID}.plist").unlink(missing_ok=True)


class _Feed:
    """A 127.0.0.1 HTTP server for the appcast; records every path asked for."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.paths: list[str] = []
        feed = self

        class Handler(http.server.SimpleHTTPRequestHandler):
            def __init__(self, *a: object, **k: object) -> None:
                super().__init__(*a, directory=str(feed.root), **k)  # type: ignore[arg-type]

            def do_GET(self) -> None:  # noqa: N802
                feed.paths.append(self.path)
                super().do_GET()

            def log_message(self, *a: object) -> None:
                pass

        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.port = self.server.server_address[1]
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    def close(self) -> None:
        self.server.shutdown()
        self.server.server_close()


@pytest.fixture(scope="module")
def probe_env() -> Iterator[dict[str, object]]:
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    _clean_probe_state()
    work = Path(tempfile.mkdtemp(prefix="lmw-updprobe-"))
    keydir = Path(tempfile.mkdtemp(prefix="lmw-updprobe-key-"))
    feed = _Feed(work / "feed")
    (work / "feed").mkdir()
    try:
        # --- build + assemble the old bundle ---------------------------------
        _run(["swift", "build", "-c", "release", "--package-path", str(REPO / "macos")])
        bin_dir = _run(
            [
                "swift",
                "build",
                "-c",
                "release",
                "--package-path",
                str(REPO / "macos"),
                "--show-bin-path",
            ]
        ).stdout.strip()
        app = work / "LM Warden.app"
        (app / "Contents" / "MacOS").mkdir(parents=True)
        shutil.copy2(Path(bin_dir) / "LMWarden", app / "Contents" / "MacOS" / "LMWarden")
        env = {k: v for k, v in os.environ.items() if not k.startswith("LMW_SPARKLE_")}
        _run(
            [
                str(MACOS / "write-info-plist.sh"),
                str(app / "Contents" / "Info.plist"),
                "1.0.0",
                "LMWarden",
                PROBE_ID,
            ],
            env=env,
        )
        _run([str(MACOS / "embed-sparkle.sh"), str(app), "--build-dir", bin_dir])

        # --- the throwaway key (never in the Keychain) -------------------------
        private = Ed25519PrivateKey.generate()
        seed = private.private_bytes(
            serialization.Encoding.Raw,
            serialization.PrivateFormat.Raw,
            serialization.NoEncryption(),
        )
        public = private.public_key()
        public_b64 = base64.b64encode(
            public.public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
        ).decode()
        keyfile = keydir / "ed25519.key"
        fd = os.open(keyfile, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(fd, "w") as f:
            f.write(base64.b64encode(seed).decode())

        # Sparkle's own sign_update, from the pinned distribution zip.
        archive = next(
            line.split("=", 1)[1]
            for line in _run([str(MACOS / "embed-sparkle.sh"), "--print-plan"]).stdout.splitlines()
            if line.startswith("archive=")
        )
        tools = work / "sparkle-tools"
        with zipfile.ZipFile(archive) as z:
            z.extract("bin/sign_update", tools)
        sign_update = tools / "bin" / "sign_update"
        sign_update.chmod(0o755)

        update = work / "feed" / "LMWarden-2.zip"
        with zipfile.ZipFile(update, "w") as z:
            z.writestr("README.txt", "throwaway update archive for the probe test\n")
        signature = _run(
            [str(sign_update), "--ed-key-file", str(keyfile), "-p", str(update)]
        ).stdout.strip()
        # The signature is over the archive with the throwaway key's public half.
        public.verify(base64.b64decode(signature), update.read_bytes())

        yield {
            "app": app,
            "feed": feed,
            "public": public_b64,
            "signature": signature,
            "length": update.stat().st_size,
            "keydir": keydir,
        }
    finally:
        feed.close()
        shutil.rmtree(keydir, ignore_errors=True)
        shutil.rmtree(work, ignore_errors=True)
        _clean_probe_state()
    assert not keydir.exists(), "the throwaway key dir must be deleted"


def _appcast(port: int, version: str, signature: str, length: int) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<rss version="2.0" xmlns:sparkle="http://www.andymatuschak.org/xml-namespaces/sparkle">
  <channel>
    <title>LM Warden probe test</title>
    <item>
      <title>{version}</title>
      <pubDate>Wed, 21 Oct 2026 12:00:00 +0000</pubDate>
      <sparkle:version>{version}</sparkle:version>
      <sparkle:shortVersionString>{version}.0.0-test</sparkle:shortVersionString>
      <enclosure url="http://127.0.0.1:{port}/LMWarden-2.zip" length="{length}"
                 type="application/octet-stream" sparkle:edSignature="{signature}"/>
    </item>
  </channel>
</rss>
"""


def _configure(app: Path, info: dict[str, object]) -> None:
    """Rewrite the bundle's plist (old CFBundleVersion 1 + `info`) and re-sign."""
    path = app / "Contents" / "Info.plist"
    with path.open("rb") as f:
        plist = plistlib.load(f)
    for key in ("SUFeedURL", "SUPublicEDKey"):
        plist.pop(key, None)
    plist["CFBundleVersion"] = "1"
    plist["CFBundleShortVersionString"] = "1.0.0"
    plist.update(info)
    with path.open("wb") as f:
        plistlib.dump(plist, f)
    _run([str(MACOS / "sign-bundle.sh"), str(app)])


def _probe(app: Path) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [str(app / "Contents" / "MacOS" / "LMWarden"), "--update-probe"],
        capture_output=True,
        text=True,
        timeout=90,
        check=False,
    )


def _enable(env: dict[str, object], version: str) -> None:
    feed = env["feed"]
    assert isinstance(feed, _Feed)
    (feed.root / "appcast.xml").write_text(
        _appcast(feed.port, version, str(env["signature"]), int(str(env["length"])))
    )
    _configure(
        Path(str(env["app"])),
        {"SUFeedURL": f"http://127.0.0.1:{feed.port}/appcast.xml", "SUPublicEDKey": env["public"]},
    )
    feed.paths.clear()


def test_old_build_detects_the_newer_item(probe_env: dict[str, object]) -> None:
    _enable(probe_env, "2")
    done = _probe(Path(str(probe_env["app"])))
    assert done.returncode == 0, done.stdout + done.stderr
    assert done.stdout.strip().splitlines()[-1] == "update-probe: available 2 2.0.0-test", (
        done.stdout + done.stderr
    )
    feed = probe_env["feed"]
    assert isinstance(feed, _Feed)
    assert any(p.startswith("/appcast.xml") for p in feed.paths), feed.paths
    # Detection only: the enclosure is never fetched.
    assert not any("LMWarden-2.zip" in p for p in feed.paths), feed.paths


def test_same_version_is_not_an_update(probe_env: dict[str, object]) -> None:
    _enable(probe_env, "1")
    done = _probe(Path(str(probe_env["app"])))
    assert done.returncode == 0, done.stdout + done.stderr
    assert done.stdout.strip().splitlines()[-1] == "update-probe: none", done.stdout + done.stderr


def test_dev_build_without_feed_is_disabled(probe_env: dict[str, object]) -> None:
    feed = probe_env["feed"]
    assert isinstance(feed, _Feed)
    _configure(Path(str(probe_env["app"])), {})
    feed.paths.clear()
    done = _probe(Path(str(probe_env["app"])))
    assert done.returncode == 3, done.stdout + done.stderr
    assert done.stdout.strip() == "update-probe: disabled"
    assert feed.paths == []
